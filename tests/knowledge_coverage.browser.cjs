/* Real browser acceptance harness. Only the isolated synthetic fixture app. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const requireLocal = require('node:module').createRequire(path.resolve(process.argv[2], 'package.json'));
const {chromium: engine} = requireLocal('playwright');
const moduleBrowser = requireLocal('@sparticuz/chromium');
const chromium = moduleBrowser.default || moduleBrowser;
const origin = process.argv[3], output = path.resolve(process.argv[4]);
assert.equal(new URL(origin).hostname, '127.0.0.1');
fs.mkdirSync(output, {recursive:true, mode:0o700});
const checks = [];
async function run() {
    chromium.setGraphicsMode = false;
    const browser = await engine.launch({executablePath:await chromium.executablePath(), args:[...chromium.args,'--disable-gpu'], headless:true});
    const context = await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true,reducedMotion:'reduce'});
    const page = await context.newPage(); const errors = [];
    page.on('pageerror',()=>errors.push('page_error'));
    await context.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
    try {
        const login = await context.request.post(origin+'/api/login',{data:{username:'planner-synthetic',password:'synthetic-browser-only'}});
        assert.equal(login.status(),200);
        await page.goto(origin+'/knowledge-coverage');
        await page.waitForSelector('#coverageRoot[data-contract="coverage-page-3"]');
        await page.keyboard.press('Tab');
        assert.equal(await page.evaluate(()=>document.activeElement.classList.contains('coverage-skip')),true);
        checks.push('signed_synthetic_auth_and_keyboard_skip');
        const queries=['مدت تأیید و مهلت ارسال درخواست چیست؟\nسؤال آزمایشی، با ویرگول',
            'Synthetic partial approval duration and cutoff?', 'Synthetic invalid citation approval duration and cutoff?',
            'مدت تأیید و مهلت ارسال درخواست چیست؟\nسؤال آزمایشی، با ویرگول', '', 'How long does it take?'];
        const q = v => '"'+v.replaceAll('"','""')+'"';
        const csv='\ufeffquery,session_id,timestamp,role\r\n'+queries.map((v,i)=>[q(v),'synthetic-'+i,'2026-01-01T12:0'+i+':00Z','user'].join(',')).join('\r\n')+'\r\n';
        await page.locator('#coverageFile').setInputFiles({name:'synthetic-browser.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
        await page.waitForFunction(()=>document.getElementById('coverageQueryColumn').value==='query');
        assert.equal(await page.locator('#coverageSessionColumn').inputValue(),'session_id');
        await page.locator('#coverageUpload').click();
        await page.waitForFunction(()=>document.getElementById('coverageRows').querySelectorAll('input[type=checkbox]').length===6);
        await page.waitForFunction(()=>document.getElementById('coverageStatus').textContent.startsWith('Input ready.'));
        assert.match(await page.locator('#coverageDatasetSummary').textContent(),/6 selected queries/);
        assert.match(await page.locator('#coverageDatasetSummary').textContent(),/Invalid input: 1/);
        await page.locator('#coverageSnapshot').selectOption({label:await page.locator('#coverageSnapshot option').filter({hasText:'2 entries'}).textContent()});
        for (let i=0;i<3;i++) await page.locator('#coverageRows input[type=checkbox]').nth(i).check();
        assert.equal(await page.locator('#coverageSelectionCount').textContent(),'3 selected / 6 imported queries');
        checks.push('csv_bom_persian_multiline_mapping_and_invalid_row_preservation');
        await page.locator('#coverageStart').click();
        await page.locator('#coverageCancel').waitFor({state:'visible'});
        await page.locator('#coverageCancel').click();
        await page.locator('#coverageResume').waitFor({state:'visible'});
        assert.match(await page.locator('#coverageProgressText').textContent(),/cancelled/i);
        const unknownCompletion = !((await page.locator('#coverageRecoveryText').textContent()).startsWith('0 request'));
        await page.locator('#coverageResume').click();
        if (unknownCompletion) {
            await page.waitForFunction(()=>document.getElementById('coverageError').textContent.includes('unknown_remote_completion_requires_choice'));
            await page.locator('#coverageRecoveryChoice').selectOption('retry_unknown');
            await page.locator('#coverageResume').click();
        }
        await page.waitForFunction(()=>document.getElementById('coverageProgressText').textContent.toLowerCase().startsWith('completed'),{},{timeout:30000});
        assert.match(await page.locator('#coverageRuns option:checked').textContent(),/completed/i);
        checks.push('background_progress_cancellation_and_pinned_retry');
        await page.locator('#coverageFilter').selectOption('covered_reachable');
        await page.waitForFunction(()=>document.getElementById('coverageRows').querySelectorAll('button').length===1);
        const review = page.locator('#coverageRows button').first();
        const reviewId = await review.getAttribute('id');
        await review.focus(); await page.keyboard.press('Enter');
        await page.waitForFunction(()=>document.getElementById('coverageEvidenceContent').textContent.includes('Supported · verified'));
        const citation = page.locator('#coverage-detail-aspects a[href^="#coverage-source-"]').first();
        await citation.click(); assert.match(new URL(page.url()).hash,/coverage-source-/);
        await page.locator('#coverageEvidence').focus(); await page.keyboard.press('Escape');
        assert.equal(await page.evaluate(()=>document.activeElement.id),reviewId);
        await review.click();
        await page.locator('#coverageEvidenceContent a[href="#coverage-detail-sources"]').click();
        await page.waitForSelector('#coverageEvidenceContent .coverage-citation');
        await page.screenshot({path:path.join(output,'desktop-dark.png')});
        await page.locator('#coverageTheme').click();
        assert.equal(await page.locator('body').evaluate(n=>n.classList.contains('light-mode')),true);
        await page.screenshot({path:path.join(output,'desktop-light.png')});
        checks.push('supported_aspects_numbered_evidence_keyboard_return_and_themes');
        await page.locator('#coverageFilter').selectOption('possible_partial_gap');
        await page.waitForFunction(()=>document.getElementById('coverageRows').querySelectorAll('button').length===1 && document.getElementById('coverageRows').textContent.includes('partial'));
        await page.locator('#coverageRows button').first().click();
        await page.waitForFunction(()=>document.getElementById('coverageEvidenceContent').textContent.includes('Missing in evaluated evidence'));
        await page.locator('#coverageFilter').selectOption('error');
        await page.waitForFunction(()=>document.getElementById('coverageRows').textContent.includes('invalid citation'));
        await page.locator('#coverageRows button').first().click();
        await page.waitForFunction(()=>document.getElementById('coverageEvidenceContent').textContent.includes('invalid_citation'));
        await page.screenshot({path:path.join(output,'error-detail-light.png')});
        checks.push('filters_missing_aspects_and_explicit_error_stopping_reason');
        await page.locator('.coverage-legacy-download summary').click();
        await page.locator('#coveragePrepareExport').click();
        await page.locator('#coverageExport').waitFor({state:'visible'});
        const csvUrl = await page.locator('#coverageExport').getAttribute('href');
        const manifestUrl = await page.locator('#coverageManifest').getAttribute('href');
        assert.equal(new URL(csvUrl,origin).searchParams.get('revision_id'),new URL(manifestUrl,origin).searchParams.get('revision_id'));
        const csvDownload = page.waitForEvent('download'); await page.locator('#coverageExport').click();
        await (await csvDownload).saveAs(path.join(output,'synthetic-export.csv'));
        const manifestDownload = page.waitForEvent('download'); await page.locator('#coverageManifest').click();
        await (await manifestDownload).saveAs(path.join(output,'synthetic-manifest.json'));
        const manifest = JSON.parse(fs.readFileSync(path.join(output,'synthetic-manifest.json'),'utf8'));
        const body = fs.readFileSync(path.join(output,'synthetic-export.csv'));
        assert.equal(body.subarray(0,3).toString('hex'),'efbbbf');
        assert.equal(crypto.createHash('sha256').update(body).digest('hex'),manifest.csv_sha256);
        assert.equal(manifest.row_count,6); assert.equal(manifest.pilot_selected_row_ids.length,3);
        checks.push('actual_csv_and_manifest_download_same_immutable_revision');
        await page.locator('#coverageFilter').selectOption('');
        await page.setViewportSize({width:390,height:844});
        await page.locator('#coverageLanguage').click();
        assert.equal(await page.locator('html').getAttribute('dir'),'rtl');
        await page.locator('#coverageResultsTitle').scrollIntoViewIfNeeded();
        await page.screenshot({path:path.join(output,'mobile-rtl-light.png')});
        assert.equal(await page.evaluate(()=>document.body.scrollWidth<=window.innerWidth),true);
        await page.locator('#coverageTheme').click();
        await page.locator('#coverageResultsTitle').scrollIntoViewIfNeeded();
        await page.screenshot({path:path.join(output,'mobile-rtl-dark.png')});
        await page.setViewportSize({width:1024,height:768});
        assert.equal(await page.evaluate(()=>document.body.scrollWidth<=window.innerWidth),true);
        checks.push('persian_rtl_responsive_390_and_1024_no_page_overflow');
        assert.deepEqual(errors,[]);
        const summary={browser_version:browser.version(),fixture:'synthetic-auth-and-artifacts-only',checks,screenshots:['desktop-dark.png','desktop-light.png','error-detail-light.png','mobile-rtl-light.png','mobile-rtl-dark.png']};
        fs.writeFileSync(path.join(output,'browser-checks.json'),JSON.stringify(summary,null,2),{mode:0o600});
        console.log(JSON.stringify(summary));
    } catch(error) {
        await page.screenshot({path:path.join(output,'failed-synthetic-check.png')});
        console.log(JSON.stringify({status:'failed',completed_checks:checks,error_type:error.name}));
        process.exitCode=1;
    } finally { await browser.close(); }
}
run().catch(()=>{console.log('Synthetic browser harness could not start.');process.exitCode=1;});
